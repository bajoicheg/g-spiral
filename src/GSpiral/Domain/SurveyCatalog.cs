    public static IReadOnlyList<CultureTypeDefinition> Types { get; } = Array.AsReadOnly(TypeData);
    public static IReadOnlyList<SurveyStageDefinition> Stages { get; } = Array.AsReadOnly(StageData);
    public static IReadOnlyList<QuestionDefinition> Questions { get; } = Array.AsReadOnly(QuestionData);
    public static IReadOnlyList<CellDefinition> Cells { get; } = Array.AsReadOnly(CellData);

    public static CultureTypeDefinition GetType(CultureTypeId id)
    {
        var index = (int)id;
        if (index < 0 || index >= TypeData.Length)
        {
            throw new ArgumentOutOfRangeException(nameof(id));
        }

        return TypeData[index];
    }

    public static CellDefinition GetCell(CultureTypeId typeId, int stageIndex)
    {
        if (stageIndex < 0 || stageIndex >= StageData.Length)
        {
            throw new ArgumentOutOfRangeException(nameof(stageIndex));
        }

        return CellData.Single(cell => cell.TypeId == typeId && cell.StageIndex == stageIndex);
    }

    public static IReadOnlyList<AtomicOptionDefinition> OptionsForStage(int stageIndex)
    {
        if (stageIndex < 0 || stageIndex >= StageData.Length)
        {
            throw new ArgumentOutOfRangeException(nameof(stageIndex));
        }

        return CellData
            .Where(cell => cell.StageIndex == stageIndex)
            .SelectMany(cell => cell.Options)
            .ToArray();
    }

    private static CellDefinition Cell(CultureTypeId typeId, int stageIndex, params string[] optionTexts)
    {
        if (optionTexts.Length is < 3 or > 6)
        {
            throw new InvalidOperationException("Each hidden cell must contain between 3 and 6 atomic options.");
        }

        var cellId = $"s{stageIndex}-t{(int)typeId}";
        var options = optionTexts
            .Select((text, index) => new AtomicOptionDefinition(
                $"{cellId}-o{index}",
                cellId,
                stageIndex,
                text))
            .ToArray();

        return new CellDefinition(cellId, typeId, stageIndex, options);
    }

    private static QuestionDefinition Q(
        int index,
        string title,
        string turquoise,
        string opportunities,
        string success,
        string rules,
        string power,
        string belonging)
    {
        var values = new Dictionary<CultureTypeId, string>
        {
            [CultureTypeId.Turquoise] = turquoise,
            [CultureTypeId.Opportunities] = opportunities,
            [CultureTypeId.Success] = success,
            [CultureTypeId.Rules] = rules,
            [CultureTypeId.Power] = power,
            [CultureTypeId.Belonging] = belonging
        };

        return new QuestionDefinition(index, title, new ReadOnlyDictionary<CultureTypeId, string>(values));
    }
